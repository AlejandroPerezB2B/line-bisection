function create_line_bisection_files()
% Creates MATLAB files for the line bisection experiment.
% No Psychtoolbox required. Uses MATLAB figures + TCP/IP.
% Updated version: robust data-folder handling for individual and shared modes.

writeFile('make_trial_orders.m', make_trial_orders_code());
writeFile('run_line_bisection_individual.m', individual_code());
writeFile('run_line_bisection_shared_host.m', host_code());
writeFile('run_line_bisection_shared_client.m', client_code());
writeFile('lb_draw_trial.m', draw_code());
writeFile('lb_get_response.m', response_code());
writeFile('lb_save_row.m', save_code());

dataDir = fullfile(pwd, 'data');
if ~exist(dataDir, 'dir')
    mkdir(dataDir);
end

disp('Created experiment files successfully.');
disp('Run make_trial_orders first.');
end

function writeFile(fname, txt)
fid = fopen(fname, 'w');
if fid < 0
    error('Could not create %s', fname);
end
fprintf(fid, '%s', txt);
fclose(fid);
end

function txt = make_trial_orders_code()
txt = [
"function orders = make_trial_orders()" newline ...
"% Fixed trial orders for all participants." newline ...
"% Individual and shared orders are different but deterministic." newline ...
"" newline ...
"positions = -900:25:900;   % 73 positions" newline ...
"positions = repmat(positions, 1, 2); % 146 trials" newline ...
"" newline ...
"rng(20260427, 'twister');" newline ...

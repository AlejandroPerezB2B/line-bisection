function txt = response_code()
txt = [
"function [resp, rtFirst, rtEnter, editTime] = lb_get_response(fig, truePos, showTyped)" newline ...
"% Typed signed integer response. Positive numbers must start with +." newline ...
"if nargin < 3; showTyped = true; end" newline ...
"" newline ...
"typed = '';" newline ...
"firstKeyTime = NaN;" newline ...
"stimTic = tic;" newline ...
"" newline ...
"while true" newline ...
"    waitforbuttonpress;" newline ...
"    ch = get(fig,'CurrentCharacter');" newline ...
"    nowT = toc(stimTic);" newline ...
"" newline ...
"    if isnan(firstKeyTime)" newline ...
"        firstKeyTime = nowT;" newline ...
"    end" newline ...
"" newline ...
"    if double(ch) == 13 || double(ch) == 10" newline ...
"        rtEnter = nowT;" newline ...
"        if isValidResponse(typed)" newline ...
"            resp = str2double(typed);" newline ...
"            rtFirst = firstKeyTime;" newline ...
"            editTime = rtEnter - rtFirst;" newline ...
"            return;" newline ...
"        else" newline ...
"            showInvalid(fig);" newline ...
"            pause(0.8);" newline ...
"            typed = '';" newline ...
"            firstKeyTime = NaN;" newline ...
"            lb_draw_trial(fig, truePos, '');" newline ...
"        end" newline ...
"    elseif double(ch) == 8" newline ...
"        if ~isempty(typed)" newline ...
"            typed = typed(1:end-1);" newline ...
"        end" newline ...
"    elseif ismember(ch, ['0':'9' '+' '-'])" newline ...
"        typed = [typed ch];" newline ...
"    end" newline ...
"" newline ...
"    if showTyped" newline ...
"        lb_draw_trial(fig, truePos, typed);" newline ...
"    end" newline ...
"end" newline ...
"end" newline ...
"" newline ...
"function tf = isValidResponse(s)" newline ...
"tf = false;" newline ...
"if isempty(s); return; end" newline ...
"if startsWith(s, '+')" newline ...
"    numpart = extractAfter(s,1);" newline ...
"    if isempty(numpart); return; end" newline ...
"elseif startsWith(s, '-')" newline ...
"    numpart = extractAfter(s,1);" newline ...
"    if isempty(numpart); return; end" newline ...
"else" newline ...
"    return;" newline ...
"end" newline ...
"if any(~isstrprop(numpart,'digit')); return; end" newline ...
"val = str2double(s);" newline ...
"tf = isfinite(val) && val >= -1000 && val <= 1000 && val == round(val);" newline ...
"end" newline ...
"" newline ...
"function showInvalid(fig)" newline ...
"clf(fig); set(fig,'Color','k');" newline ...
"text(0.5,0.5,'Please enter a number between -1000 and 1000', ..." newline ...
"    'Color','w','HorizontalAlignment','center','FontSize',24,'Units','normalized');" newline ...
"axis off; drawnow;" newline ...
"end" newline ...
];
end

function txt = save_code()

"function run_line_bisection_shared_host(dyadID, participantID, port)" newline ...
"if nargin < 1 || isempty(dyadID); dyadID = input('Dyad ID, e.g. dyad001: ', 's'); end" newline ...
"if nargin < 2 || isempty(participantID); participantID = [dyadID '_A']; end" newline ...
"if nargin < 3 || isempty(port); port = 50000; end" newline ...
"" newline ...
"if ~exist('trial_orders.mat', 'file'); make_trial_orders(); end" newline ...
"load('trial_orders.mat', 'orders');" newline ...
"trials = orders.shared;" newline ...
"" newline ...

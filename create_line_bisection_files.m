"function waitForClientDone(srv, trialNum)" newline ...
"while true" newline ...
"    if srv.NumBytesAvailable > 0" newline ...
"        msg = char(readline(srv));" newline ...
"        if startsWith(msg, sprintf('DONE|%d|CLIENT', trialNum))" newline ...
"            return;" newline ...
"        end" newline ...
"    end" newline ...
"    pause(0.01);" newline ...
"end" newline ...
"end" newline ...
];
end

function txt = client_code()
txt = [
"function run_line_bisection_shared_client(dyadID, participantID, hostIP, port)" newline ...
"if nargin < 1 || isempty(dyadID); dyadID = input('Dyad ID, e.g. dyad001: ', 's'); end" newline ...
"if nargin < 2 || isempty(participantID); participantID = [dyadID '_B']; end" newline ...
"if nargin < 3 || isempty(hostIP); hostIP = input('Host IP address: ', 's'); end" newline ...
"if nargin < 4 || isempty(port); port = 50000; end" newline ...
"" newline ...
"if ~exist('trial_orders.mat', 'file'); make_trial_orders(); end" newline ...
"load('trial_orders.mat', 'orders');" newline ...
"trials = orders.shared;" newline ...
"" newline ...
"dataDir = fullfile(pwd, 'data');" newline ...
"if ~exist(dataDir, 'dir')" newline ...
"    mkdir(dataDir);" newline ...
"end" newline ...
"localFile = fullfile(dataDir, [participantID '_shared.csv']);" newline ...
"" newline ...
"disp(['Connecting to host ' hostIP ':' num2str(port)]);" newline ...
"cli = tcpclient(hostIP, port, 'Timeout', 60);" newline ...
"configureTerminator(cli, 'LF');" newline ...
"pause(0.5);" newline ...
"" newline ...
"fig = figure('Color','k','MenuBar','none','ToolBar','none','NumberTitle','off', ..." newline ...
"    'Name','Line Bisection - Shared Client','KeyPressFcn',@(~,~)[]);" newline ...
"set(fig, 'WindowState', 'maximized'); drawnow;" newline ...
"" newline ...
"for t = 1:numel(trials)" newline ...
"    clf(fig);" newline ...
"    text(0.5,0.5,sprintf(['Trial %d of %d\n\nYou and your partner will see the same line.\n' ..." newline ...
"        'Work silently and enter only your own estimate.\n\nEither participant may press SPACE to start.'], t, numel(trials)), ..." newline ...
"        'Color','w','HorizontalAlignment','center','FontSize',22,'Units','normalized');" newline ...
"    axis off; drawnow;" newline ...
"" newline ...
"    waitForStartOrSendSpace(fig, cli);" newline ...
"    [trialNum, truePos, triggeredBy] = waitForStartMessage(cli);" newline ...
"    if trialNum ~= t" newline ...
"        error('Trial mismatch: expected %d, got %d', t, trialNum);" newline ...
"    end" newline ...
"" newline ...
"    lb_draw_trial(fig, truePos, '');" newline ...
"    [resp, rtFirst, rtEnter, editTime] = lb_get_response(fig, truePos, true);" newline ...
"    writeline(cli, sprintf('DONE|%d|CLIENT', t));" newline ...
"" newline ...
"    row = table({participantID}, {'shared'}, t, truePos, resp, resp-truePos, ..." newline ...
"        rtFirst, rtEnter, editTime, NaN, {triggeredBy}, datetime('now'), ..." newline ...
"        'VariableNames', {'participantID','condition','trial','truePosition','response','error', ..." newline ...
"        'RT_firstKey','RT_enter','editingTime','ITI','triggeredBy','timestamp'});" newline ...
"    lb_save_row(localFile, row);" newline ...
"" newline ...
"    iti = waitForITI(cli);" newline ...
"    clf(fig); set(fig,'Color','k'); axis off; drawnow; pause(iti);" newline ...
"end" newline ...
"" newline ...
"clf(fig); text(0.5,0.5,'Finished. Thank you.','Color','w','HorizontalAlignment','center','FontSize',28,'Units','normalized'); axis off;" newline ...
"end" newline ...
"" newline ...
"function waitForStartOrSendSpace(fig, cli)" newline ...
"set(fig, 'CurrentCharacter', char(0));" newline ...
"sent = false;" newline ...
"while true" newline ...
"    drawnow;" newline ...
"    if cli.NumBytesAvailable > 0" newline ...
"        return;" newline ...
"    end" newline ...
"    ch = get(fig, 'CurrentCharacter');" newline ...
"    if strcmp(ch, ' ') && ~sent" newline ...
"        writeline(cli, 'SPACE|CLIENT');" newline ...
"        sent = true;" newline ...
"        set(fig, 'CurrentCharacter', char(0));" newline ...
"    end" newline ...
"    pause(0.01);" newline ...
"end" newline ...
"end" newline ...
"" newline ...
"function [trialNum, truePos, triggeredBy] = waitForStartMessage(cli)" newline ...
"while true" newline ...
"    if cli.NumBytesAvailable > 0" newline ...
"        msg = char(readline(cli));" newline ...
"        if startsWith(msg, 'START')" newline ...
"            parts = split(msg, '|');" newline ...
"            trialNum = str2double(parts{2});" newline ...
"            truePos = str2double(parts{3});" newline ...
"            triggeredBy = parts{4};" newline ...
"            return;" newline ...
"        end" newline ...
"    end" newline ...
"    pause(0.01);" newline ...
"end" newline ...
"end" newline ...
"" newline ...
"function iti = waitForITI(cli)" newline ...
"iti = 0.4;" newline ...
"while true" newline ...
"    if cli.NumBytesAvailable > 0" newline ...
"        msg = char(readline(cli));" newline ...
"        if startsWith(msg, 'ITI')" newline ...
"            parts = split(msg, '|');" newline ...
"            iti = str2double(parts{2});" newline ...
"            return;" newline ...
"        elseif startsWith(msg, 'FINISHED')" newline ...
"            return;" newline ...
"        end" newline ...
"    end" newline ...
"    pause(0.01);" newline ...
"end" newline ...
"end" newline ...
];
end


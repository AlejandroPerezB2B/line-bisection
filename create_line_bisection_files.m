"        'Color','w','HorizontalAlignment','center','FontSize',22,'Units','normalized');" newline ...
"    axis off; drawnow;" newline ...
"" newline ...
"    triggeredBy = waitForSharedSpaceHost(fig, srv);" newline ...
"    msg = sprintf('START|%d|%d|%s', t, truePos, triggeredBy);" newline ...
"    writeline(srv, msg);" newline ...
"" newline ...
"    lb_draw_trial(fig, truePos, '');" newline ...
"    [resp, rtFirst, rtEnter, editTime] = lb_get_response(fig, truePos, true);" newline ...
"    localDoneTime = datetime('now');" newline ...
"    writeline(srv, sprintf('DONE|%d|HOST', t));" newline ...
"" newline ...
"    waitForClientDone(srv, t);" newline ...
"" newline ...
"    row = table({participantID}, {'shared'}, t, truePos, resp, resp-truePos, ..." newline ...
"        rtFirst, rtEnter, editTime, NaN, {triggeredBy}, localDoneTime, ..." newline ...
"        'VariableNames', {'participantID','condition','trial','truePosition','response','error', ..." newline ...
"        'RT_firstKey','RT_enter','editingTime','ITI','triggeredBy','timestamp'});" newline ...
"    lb_save_row(localFile, row);" newline ...
"" newline ...
"    syncRow = table({dyadID}, t, truePos, {triggeredBy}, datetime('now'), ..." newline ...
"        'VariableNames', {'dyadID','trial','truePosition','triggeredBy','timestamp'});" newline ...
"    lb_save_row(syncFile, syncRow);" newline ...
"" newline ...
"    iti = 0.3 + rand()*0.2;" newline ...
"    writeline(srv, sprintf('ITI|%.3f', iti));" newline ...
"    clf(fig); set(fig,'Color','k'); axis off; drawnow; pause(iti);" newline ...
"end" newline ...
"" newline ...
"writeline(srv, 'FINISHED');" newline ...
"clf(fig); text(0.5,0.5,'Finished. Thank you.','Color','w','HorizontalAlignment','center','FontSize',28,'Units','normalized'); axis off;" newline ...
"end" newline ...
"" newline ...
"function triggeredBy = waitForSharedSpaceHost(fig, srv)" newline ...
"triggeredBy = '';" newline ...
"set(fig, 'CurrentCharacter', char(0));" newline ...
"while isempty(triggeredBy)" newline ...
"    drawnow;" newline ...
"    ch = get(fig, 'CurrentCharacter');" newline ...
"    if strcmp(ch, ' ')" newline ...
"        triggeredBy = 'HOST';" newline ...
"        set(fig, 'CurrentCharacter', char(0));" newline ...
"        return;" newline ...
"    end" newline ...
"    if srv.NumBytesAvailable > 0" newline ...
"        msg = char(readline(srv));" newline ...
"        if startsWith(msg, 'SPACE')" newline ...
"            triggeredBy = 'CLIENT';" newline ...
"            return;" newline ...
"        end" newline ...
"    end" newline ...
"    pause(0.01);" newline ...
"end" newline ...
"end" newline ...

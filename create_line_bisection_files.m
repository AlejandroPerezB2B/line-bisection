"function lb_save_row(outfile, row)" newline ...
"% Make sure the output folder exists before writing the file." newline ...
"[folder, ~, ~] = fileparts(outfile);" newline ...
"" newline ...
"if ~isempty(folder) && ~exist(folder, 'dir')" newline ...
"    mkdir(folder);" newline ...
"end" newline ...
"" newline ...
"% Save row. If the file exists, append. If not, create it." newline ...
"if exist(outfile, 'file')" newline ...
"    writetable(row, outfile, 'WriteMode', 'append');" newline ...
"else" newline ...
"    writetable(row, outfile);" newline ...
"end" newline ...
"" newline ...
"end" newline ...
];
end
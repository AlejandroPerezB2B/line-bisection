"    mkdir(dataDir);" newline ...
"end" newline ...
"localFile = fullfile(dataDir, [participantID '_shared.csv']);" newline ...
"syncFile = fullfile(dataDir, [dyadID '_shared_sync.csv']);" newline ...
"" newline ...
"disp(['Starting TCP server on port ' num2str(port)]);" newline ...
"srv = tcpserver('0.0.0.0', port, 'Timeout', 60);" newline ...
"configureTerminator(srv, 'LF');" newline ...
"disp('Waiting for client...');" newline ...
"while srv.Connected == 0; pause(0.1); end" newline ...
"disp('Client connected.');" newline ...
"writeline(srv, 'HELLO_FROM_HOST');" newline ...
"" newline ...
"fig = figure('Color','k','MenuBar','none','ToolBar','none','NumberTitle','off', ..." newline ...
"    'Name','Line Bisection - Shared Host','KeyPressFcn',@(~,~)[]);" newline ...
"set(fig, 'WindowState', 'maximized'); drawnow;" newline ...
"" newline ...
"for t = 1:numel(trials)" newline ...
"    truePos = trials(t);" newline ...
"    clf(fig);" newline ...
"    text(0.5,0.5,sprintf(['Trial %d of %d\n\nYou and your partner will see the same line.\n' ..." newline ...
